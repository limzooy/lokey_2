export type Category = {
  slug: string;
  name: string;
  korean: string;
  description: string;
  image: string;
};

export type Section = {
  heading?: string;
  body: string;
  /** 문단 아래에 넣을 그래프·사진 (public/ 경로) */
  image?: string;
  imageAlt?: string;
  /** 이미지 밑에 작게 붙는 설명 */
  caption?: string;
};

export type Source = {
  label: string;
  url: string;
};

/**
 * 발행 후 사실관계가 바뀌었을 때 글 맨 위에 붙는 정정 알림.
 * 원문을 몰래 고치지 않고 무엇이 틀렸는지 남긴다.
 */
export type Correction = {
  /** 화면에 붙는 말머리. 생략하면 '정정' */
  label?: string;
  date: string;
  body: string;
  link?: { label: string; slug: string };
};

export type Post = {
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  date: string;
  image: string;
  imageAlt: string;
  lead: string;
  sections: Section[];
  /** 데이터 기반 글이면 출처를 남긴다. 독자가 검증할 수 있어야 한다. */
  sources?: Source[];
  correction?: Correction;
};

